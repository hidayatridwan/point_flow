-- Redesign products into product masters and package-level SKUs.
-- Safe to run on the old schema; mostly no-op on a fresh schema that already includes product_skus.

BEGIN;

DO $$
BEGIN
    CREATE TYPE stock_conversion_status AS ENUM ('draft', 'posted', 'cancelled');
EXCEPTION
    WHEN duplicate_object THEN NULL;
END $$;

ALTER TYPE stock_movement_type ADD VALUE IF NOT EXISTS 'conversion_in';
ALTER TYPE stock_movement_type ADD VALUE IF NOT EXISTS 'conversion_out';

CREATE TABLE IF NOT EXISTS units (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(30) NOT NULL,
    name VARCHAR(80) NOT NULL,
    allow_decimal BOOLEAN NOT NULL DEFAULT FALSE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at TIMESTAMPTZ
);

CREATE UNIQUE INDEX IF NOT EXISTS units_code_unique_idx
    ON units (lower(code))
    WHERE deleted_at IS NULL;

INSERT INTO units (code, name, allow_decimal)
SELECT seed.code, seed.name, seed.allow_decimal
FROM (
    VALUES
        ('pcs', 'Pieces', FALSE),
        ('dus', 'Dus', FALSE),
        ('pack', 'Pack', FALSE),
        ('box', 'Box', FALSE),
        ('kg', 'Kilogram', TRUE),
        ('gram', 'Gram', TRUE),
        ('liter', 'Liter', TRUE),
        ('ml', 'Milliliter', TRUE)
) AS seed(code, name, allow_decimal)
WHERE NOT EXISTS (
    SELECT 1 FROM units u WHERE lower(u.code) = lower(seed.code) AND u.deleted_at IS NULL
);

CREATE TABLE IF NOT EXISTS product_skus (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
    sku VARCHAR(64) NOT NULL,
    barcode VARCHAR(80),
    unit_id BIGINT NOT NULL REFERENCES units(id) ON DELETE RESTRICT,
    contents_qty NUMERIC(14, 3) NOT NULL DEFAULT 1,
    purchase_price NUMERIC(14, 2) NOT NULL DEFAULT 0,
    selling_price NUMERIC(14, 2) NOT NULL DEFAULT 0,
    stock NUMERIC(14, 3) NOT NULL DEFAULT 0,
    minimum_stock NUMERIC(14, 3) NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at TIMESTAMPTZ,
    CONSTRAINT product_skus_contents_qty_positive CHECK (contents_qty > 0),
    CONSTRAINT product_skus_purchase_price_non_negative CHECK (purchase_price >= 0),
    CONSTRAINT product_skus_selling_price_non_negative CHECK (selling_price >= 0),
    CONSTRAINT product_skus_stock_non_negative CHECK (stock >= 0),
    CONSTRAINT product_skus_minimum_stock_non_negative CHECK (minimum_stock >= 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS product_skus_sku_unique_idx
    ON product_skus (lower(sku))
    WHERE deleted_at IS NULL;

CREATE UNIQUE INDEX IF NOT EXISTS product_skus_barcode_unique_idx
    ON product_skus (lower(barcode))
    WHERE deleted_at IS NULL AND barcode IS NOT NULL;

CREATE INDEX IF NOT EXISTS product_skus_product_idx ON product_skus (product_id);
CREATE INDEX IF NOT EXISTS product_skus_unit_idx ON product_skus (unit_id);
CREATE INDEX IF NOT EXISTS product_skus_sku_search_idx ON product_skus (lower(sku));
CREATE INDEX IF NOT EXISTS product_skus_barcode_search_idx ON product_skus (lower(barcode));
CREATE INDEX IF NOT EXISTS product_skus_low_stock_idx
    ON product_skus (stock, minimum_stock)
    WHERE deleted_at IS NULL AND is_active = TRUE AND stock <= minimum_stock;

DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'products' AND column_name = 'sku'
    ) THEN
        EXECUTE $units$
            INSERT INTO units (code, name, allow_decimal)
            SELECT DISTINCT p.unit, p.unit, TRUE
            FROM products p
            WHERE NOT EXISTS (
                SELECT 1 FROM units u WHERE lower(u.code) = lower(p.unit) AND u.deleted_at IS NULL
            )
        $units$;
        EXECUTE $migrate$
            INSERT INTO product_skus (
                product_id, sku, unit_id, contents_qty, purchase_price, selling_price,
                stock, minimum_stock, is_active, created_at, updated_at, deleted_at
            )
            SELECT
                p.id,
                p.sku,
                u.id,
                1,
                p.purchase_price,
                p.selling_price,
                p.stock,
                p.minimum_stock,
                p.is_active,
                p.created_at,
                p.updated_at,
                p.deleted_at
            FROM products p
            JOIN units u ON lower(u.code) = lower(p.unit)
            WHERE NOT EXISTS (
                SELECT 1 FROM product_skus ps
                WHERE ps.product_id = p.id AND lower(ps.sku) = lower(p.sku)
            )
        $migrate$;
    END IF;
END $$;

ALTER TABLE purchase_order_items ADD COLUMN IF NOT EXISTS product_sku_id BIGINT REFERENCES product_skus(id) ON DELETE RESTRICT;
ALTER TABLE goods_receipt_items ADD COLUMN IF NOT EXISTS product_sku_id BIGINT REFERENCES product_skus(id) ON DELETE RESTRICT;
ALTER TABLE stock_adjustment_items ADD COLUMN IF NOT EXISTS product_sku_id BIGINT REFERENCES product_skus(id) ON DELETE RESTRICT;
ALTER TABLE sale_items ADD COLUMN IF NOT EXISTS product_sku_id BIGINT REFERENCES product_skus(id) ON DELETE RESTRICT;
ALTER TABLE stock_movements ADD COLUMN IF NOT EXISTS product_sku_id BIGINT REFERENCES product_skus(id) ON DELETE RESTRICT;

UPDATE purchase_order_items poi
SET product_sku_id = ps.id
FROM product_skus ps
WHERE poi.product_sku_id IS NULL AND ps.product_id = poi.product_id;

UPDATE goods_receipt_items gri
SET product_sku_id = ps.id
FROM product_skus ps
WHERE gri.product_sku_id IS NULL AND ps.product_id = gri.product_id;

UPDATE stock_adjustment_items sai
SET product_sku_id = ps.id
FROM product_skus ps
WHERE sai.product_sku_id IS NULL AND ps.product_id = sai.product_id;

UPDATE sale_items si
SET product_sku_id = ps.id
FROM product_skus ps
WHERE si.product_sku_id IS NULL AND ps.product_id = si.product_id;

UPDATE stock_movements sm
SET product_sku_id = ps.id
FROM product_skus ps
WHERE sm.product_sku_id IS NULL AND ps.product_id = sm.product_id;

ALTER TABLE purchase_order_items ALTER COLUMN product_sku_id SET NOT NULL;
ALTER TABLE goods_receipt_items ALTER COLUMN product_sku_id SET NOT NULL;
ALTER TABLE stock_adjustment_items ALTER COLUMN product_sku_id SET NOT NULL;
ALTER TABLE sale_items ALTER COLUMN product_sku_id SET NOT NULL;
ALTER TABLE stock_movements ALTER COLUMN product_sku_id SET NOT NULL;

DROP INDEX IF EXISTS purchase_order_items_order_product_unique_idx;
CREATE UNIQUE INDEX IF NOT EXISTS purchase_order_items_order_sku_unique_idx
    ON purchase_order_items (purchase_order_id, product_sku_id);
CREATE INDEX IF NOT EXISTS purchase_order_items_product_sku_idx ON purchase_order_items (product_sku_id);

CREATE INDEX IF NOT EXISTS goods_receipt_items_product_sku_idx ON goods_receipt_items (product_sku_id);

DROP INDEX IF EXISTS stock_adjustment_items_adjustment_product_unique_idx;
CREATE UNIQUE INDEX IF NOT EXISTS stock_adjustment_items_adjustment_sku_unique_idx
    ON stock_adjustment_items (stock_adjustment_id, product_sku_id);
CREATE INDEX IF NOT EXISTS stock_adjustment_items_product_sku_idx ON stock_adjustment_items (product_sku_id);

CREATE INDEX IF NOT EXISTS sale_items_product_sku_idx ON sale_items (product_sku_id);
CREATE INDEX IF NOT EXISTS stock_movements_product_sku_idx ON stock_movements (product_sku_id);

CREATE SEQUENCE IF NOT EXISTS stock_conversion_no_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE IF NOT EXISTS stock_conversions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversion_no VARCHAR(40) NOT NULL DEFAULT (
        'CONV-' || to_char(now(), 'YYYYMMDD') || '-' ||
        lpad(nextval('stock_conversion_no_seq')::TEXT, 6, '0')
    ),
    converted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    status stock_conversion_status NOT NULL DEFAULT 'draft',
    notes TEXT,
    created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    posted_at TIMESTAMPTZ,
    posted_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    cancelled_at TIMESTAMPTZ,
    cancelled_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    cancel_reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS stock_conversions_conversion_no_unique_idx ON stock_conversions (conversion_no);
CREATE INDEX IF NOT EXISTS stock_conversions_converted_at_idx ON stock_conversions (converted_at);
CREATE INDEX IF NOT EXISTS stock_conversions_status_idx ON stock_conversions (status);

CREATE TABLE IF NOT EXISTS stock_conversion_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stock_conversion_id BIGINT NOT NULL REFERENCES stock_conversions(id) ON DELETE CASCADE,
    from_product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
    from_product_sku_id BIGINT NOT NULL REFERENCES product_skus(id) ON DELETE RESTRICT,
    from_product_name VARCHAR(160) NOT NULL,
    from_product_sku VARCHAR(64) NOT NULL,
    from_unit VARCHAR(30) NOT NULL,
    from_stock_before NUMERIC(14, 3) NOT NULL,
    from_quantity NUMERIC(14, 3) NOT NULL,
    from_stock_after NUMERIC(14, 3) NOT NULL,
    to_product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
    to_product_sku_id BIGINT NOT NULL REFERENCES product_skus(id) ON DELETE RESTRICT,
    to_product_name VARCHAR(160) NOT NULL,
    to_product_sku VARCHAR(64) NOT NULL,
    to_unit VARCHAR(30) NOT NULL,
    to_stock_before NUMERIC(14, 3) NOT NULL,
    to_quantity NUMERIC(14, 3) NOT NULL,
    to_stock_after NUMERIC(14, 3) NOT NULL,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT stock_conversion_items_distinct_skus CHECK (from_product_sku_id <> to_product_sku_id),
    CONSTRAINT stock_conversion_items_same_product CHECK (from_product_id = to_product_id),
    CONSTRAINT stock_conversion_items_from_quantity_positive CHECK (from_quantity > 0),
    CONSTRAINT stock_conversion_items_to_quantity_positive CHECK (to_quantity > 0),
    CONSTRAINT stock_conversion_items_from_stock_before_non_negative CHECK (from_stock_before >= 0),
    CONSTRAINT stock_conversion_items_from_stock_after_non_negative CHECK (from_stock_after >= 0),
    CONSTRAINT stock_conversion_items_to_stock_before_non_negative CHECK (to_stock_before >= 0),
    CONSTRAINT stock_conversion_items_to_stock_after_non_negative CHECK (to_stock_after >= 0),
    CONSTRAINT stock_conversion_items_from_stock_matches CHECK (from_stock_after = from_stock_before - from_quantity),
    CONSTRAINT stock_conversion_items_to_stock_matches CHECK (to_stock_after = to_stock_before + to_quantity)
);

CREATE INDEX IF NOT EXISTS stock_conversion_items_conversion_idx ON stock_conversion_items (stock_conversion_id);
CREATE INDEX IF NOT EXISTS stock_conversion_items_from_product_sku_idx ON stock_conversion_items (from_product_sku_id);
CREATE INDEX IF NOT EXISTS stock_conversion_items_to_product_sku_idx ON stock_conversion_items (to_product_sku_id);

ALTER TABLE stock_movements ADD COLUMN IF NOT EXISTS stock_conversion_id BIGINT REFERENCES stock_conversions(id) ON DELETE SET NULL;
ALTER TABLE stock_movements ADD COLUMN IF NOT EXISTS stock_conversion_item_id BIGINT REFERENCES stock_conversion_items(id) ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS stock_movements_stock_conversion_idx ON stock_movements (stock_conversion_id);

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'units_set_updated_at') THEN
        CREATE TRIGGER units_set_updated_at
            BEFORE UPDATE ON units
            FOR EACH ROW EXECUTE FUNCTION set_updated_at();
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'product_skus_set_updated_at') THEN
        CREATE TRIGGER product_skus_set_updated_at
            BEFORE UPDATE ON product_skus
            FOR EACH ROW EXECUTE FUNCTION set_updated_at();
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'stock_conversions_set_updated_at') THEN
        CREATE TRIGGER stock_conversions_set_updated_at
            BEFORE UPDATE ON stock_conversions
            FOR EACH ROW EXECUTE FUNCTION set_updated_at();
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'stock_conversion_items_set_updated_at') THEN
        CREATE TRIGGER stock_conversion_items_set_updated_at
            BEFORE UPDATE ON stock_conversion_items
            FOR EACH ROW EXECUTE FUNCTION set_updated_at();
    END IF;
END $$;

DROP VIEW IF EXISTS v_stock_report;

CREATE OR REPLACE VIEW v_stock_report AS
SELECT
    ps.id AS product_sku_id,
    p.id AS product_id,
    p.name AS product_name,
    ps.sku,
    ps.barcode,
    c.name AS category_name,
    ps.purchase_price,
    ps.selling_price,
    ps.stock,
    ps.minimum_stock,
    u.code AS unit,
    COALESCE((
        SELECT SUM(poi.quantity_ordered - poi.quantity_received)
        FROM purchase_order_items poi
        JOIN purchase_orders po ON po.id = poi.purchase_order_id
        WHERE poi.product_sku_id = ps.id
            AND po.status IN ('ordered', 'partially_received')
    ), 0) AS quantity_on_order,
    (ps.stock <= ps.minimum_stock) AS is_low_stock,
    (p.is_active AND ps.is_active) AS is_active
FROM products p
JOIN product_skus ps ON ps.product_id = p.id
LEFT JOIN product_categories c ON c.id = p.category_id
JOIN units u ON u.id = ps.unit_id
WHERE p.deleted_at IS NULL AND ps.deleted_at IS NULL;

COMMIT;
