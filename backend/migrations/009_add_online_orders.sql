-- PostgreSQL migration: public storefront online orders (MVP).
-- New order tables, store settings, sales channel marker, product photos,
-- and the online_orders RBAC permission (granted to admin and cashier).

BEGIN;

CREATE TYPE online_order_status AS ENUM (
    'new',
    'packing',
    'ready',
    'delivering',
    'completed',
    'cancelled'
);

CREATE TYPE online_order_fulfillment_method AS ENUM (
    'pickup',
    'delivery'
);

CREATE TYPE online_order_payment_method AS ENUM (
    'pay_at_store',
    'transfer'
);

CREATE TYPE online_order_payment_status AS ENUM (
    'unpaid',
    'paid'
);

CREATE SEQUENCE online_order_no_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE online_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no VARCHAR(40) NOT NULL DEFAULT (
        'ONL-' || to_char(now(), 'YYYYMMDD') || '-' ||
        lpad(nextval('online_order_no_seq')::TEXT, 6, '0')
    ),
    customer_name VARCHAR(120) NOT NULL,
    customer_phone VARCHAR(30) NOT NULL,
    fulfillment_method online_order_fulfillment_method NOT NULL,
    delivery_address TEXT,
    payment_method online_order_payment_method NOT NULL,
    payment_status online_order_payment_status NOT NULL DEFAULT 'unpaid',
    status online_order_status NOT NULL DEFAULT 'new',
    subtotal_amount NUMERIC(14, 2) NOT NULL DEFAULT 0,
    delivery_fee NUMERIC(14, 2) NOT NULL DEFAULT 0,
    total_amount NUMERIC(14, 2) NOT NULL DEFAULT 0,
    notes TEXT,
    sale_id BIGINT REFERENCES sales(id),
    processed_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    cancel_reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT online_orders_customer_name_required CHECK (length(trim(customer_name)) > 0),
    CONSTRAINT online_orders_customer_phone_required CHECK (length(trim(customer_phone)) > 0),
    CONSTRAINT online_orders_delivery_address_required CHECK (
        fulfillment_method <> 'delivery'
        OR (delivery_address IS NOT NULL AND length(trim(delivery_address)) > 0)
    ),
    CONSTRAINT online_orders_subtotal_non_negative CHECK (subtotal_amount >= 0),
    CONSTRAINT online_orders_delivery_fee_non_negative CHECK (delivery_fee >= 0),
    CONSTRAINT online_orders_total_matches CHECK (total_amount = subtotal_amount + delivery_fee)
);

CREATE UNIQUE INDEX online_orders_no_unique_idx ON online_orders (order_no);
CREATE INDEX online_orders_status_idx ON online_orders (status);
CREATE INDEX online_orders_created_at_idx ON online_orders (created_at DESC);
CREATE INDEX online_orders_sale_idx ON online_orders (sale_id);

CREATE TRIGGER online_orders_set_updated_at
    BEFORE UPDATE ON online_orders
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE online_order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    online_order_id BIGINT NOT NULL REFERENCES online_orders(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
    product_sku_id BIGINT NOT NULL REFERENCES product_skus(id) ON DELETE RESTRICT,
    product_name VARCHAR(160) NOT NULL,
    product_sku VARCHAR(64) NOT NULL,
    unit VARCHAR(30) NOT NULL,
    quantity NUMERIC(14, 3) NOT NULL,
    unit_price NUMERIC(14, 2) NOT NULL,
    line_total NUMERIC(14, 2) GENERATED ALWAYS AS (quantity * unit_price) STORED,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT online_order_items_quantity_positive CHECK (quantity > 0),
    CONSTRAINT online_order_items_unit_price_non_negative CHECK (unit_price >= 0)
);

CREATE INDEX online_order_items_order_idx ON online_order_items (online_order_id);
CREATE INDEX online_order_items_product_sku_idx ON online_order_items (product_sku_id);

CREATE TABLE store_settings (
    key VARCHAR(80) PRIMARY KEY,
    value TEXT NOT NULL DEFAULT '',
    updated_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TRIGGER store_settings_set_updated_at
    BEFORE UPDATE ON store_settings
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

INSERT INTO store_settings (key, value)
VALUES
    ('store_name', ''),
    ('operating_hours', ''),
    ('bank_accounts', ''),
    ('ewallet_numbers', ''),
    ('qris_image_key', ''),
    ('delivery_fee', '0');

ALTER TABLE sales
    ADD COLUMN channel VARCHAR(20) NOT NULL DEFAULT 'point_flow',
    ADD COLUMN online_order_id BIGINT REFERENCES online_orders(id);

ALTER TABLE sales
    ADD CONSTRAINT sales_channel_valid CHECK (channel IN ('point_flow', 'online'));

CREATE UNIQUE INDEX sales_online_order_unique_idx ON sales (online_order_id);

ALTER TABLE products
    ADD COLUMN image_url VARCHAR(500);

ALTER TABLE products
    ADD CONSTRAINT products_image_url_non_empty CHECK (
        image_url IS NULL OR length(trim(image_url)) > 0
    );

INSERT INTO permissions (code, name, description)
VALUES (
    'online_orders',
    'Online Orders',
    'Access public storefront order management and fulfillment workflows.'
);

INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id
FROM roles r
CROSS JOIN permissions p
WHERE p.code = 'online_orders'
AND r.code IN ('admin', 'cashier');

COMMIT;
