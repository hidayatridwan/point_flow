-- PostgreSQL migration: profit sharing (SHU) periods + distribution snapshots.
-- Allocation buckets are fixed columns for v1 (must total 100%).

BEGIN;

CREATE TYPE profit_sharing_period_status AS ENUM (
    'draft',
    'calculated',
    'finalized',
    'cancelled'
);

CREATE TABLE profit_sharing_periods (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    period_name VARCHAR(60) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    status profit_sharing_period_status NOT NULL DEFAULT 'draft',
    total_pool NUMERIC(14, 2),
    auto_net_profit NUMERIC(14, 2),
    member_pct NUMERIC(5, 2) NOT NULL,
    reserve_pct NUMERIC(5, 2) NOT NULL,
    management_pct NUMERIC(5, 2) NOT NULL,
    supervisor_pct NUMERIC(5, 2) NOT NULL,
    social_pct NUMERIC(5, 2) NOT NULL,
    education_pct NUMERIC(5, 2) NOT NULL,
    CONSTRAINT profit_sharing_periods_pct_sum CHECK (
        member_pct + reserve_pct + management_pct + supervisor_pct
        + social_pct + education_pct = 100
    ),
    CONSTRAINT profit_sharing_periods_dates_valid CHECK (start_date <= end_date),
    notes TEXT,
    calculated_at TIMESTAMPTZ,
    finalized_at TIMESTAMPTZ,
    finalized_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    cancelled_at TIMESTAMPTZ,
    cancelled_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    cancel_reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE profit_sharing_distributions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profit_sharing_period_id BIGINT NOT NULL
        REFERENCES profit_sharing_periods(id) ON DELETE CASCADE,
    member_id BIGINT NOT NULL REFERENCES members(id) ON DELETE RESTRICT,
    transaction_amount NUMERIC(14, 2) NOT NULL,
    share_pct NUMERIC(7, 4) NOT NULL,
    share_amount NUMERIC(14, 2) NOT NULL,
    calculated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT profit_sharing_distributions_period_member_unique
        UNIQUE (profit_sharing_period_id, member_id)
);

CREATE INDEX profit_sharing_periods_status_idx
    ON profit_sharing_periods (status);

CREATE INDEX profit_sharing_periods_dates_idx
    ON profit_sharing_periods (start_date, end_date);

CREATE INDEX profit_sharing_distributions_period_idx
    ON profit_sharing_distributions (profit_sharing_period_id);

CREATE INDEX profit_sharing_distributions_member_idx
    ON profit_sharing_distributions (member_id);

CREATE TRIGGER profit_sharing_periods_set_updated_at
    BEFORE UPDATE ON profit_sharing_periods
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

INSERT INTO permissions (code, name, description)
VALUES (
    'profit_sharing',
    'Profit Sharing',
    'Manage profit sharing (SHU) periods, calculations, and distributions.'
);

INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id
FROM roles r
CROSS JOIN permissions p
WHERE p.code = 'profit_sharing'
AND r.code = 'admin';

COMMIT;
