-- PostgreSQL migration: manual financial records (income/expense) + COGS snapshot foundation.

BEGIN;

CREATE TYPE financial_transaction_type AS ENUM (
    'income',
    'expense'
);

CREATE TYPE financial_transaction_status AS ENUM (
    'completed',
    'cancelled'
);

CREATE SEQUENCE financial_transactions_no_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE financial_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    type financial_transaction_type NOT NULL,
    description TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_by BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT financial_categories_name_type_unique UNIQUE (name, type)
);

CREATE TABLE financial_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_no VARCHAR(40) NOT NULL DEFAULT (
        'FIN-' || to_char(now(), 'YYYYMMDD') || '-' ||
        lpad(nextval('financial_transactions_no_seq')::TEXT, 6, '0')
    ),
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    type financial_transaction_type NOT NULL,
    financial_category_id BIGINT NOT NULL REFERENCES financial_categories(id) ON DELETE RESTRICT,
    amount NUMERIC(14, 2) NOT NULL,
    is_cash BOOLEAN NOT NULL DEFAULT TRUE,
    description TEXT,
    status financial_transaction_status NOT NULL DEFAULT 'completed',
    cancelled_at TIMESTAMPTZ,
    cancelled_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    cancel_reason TEXT,
    recorded_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT financial_transactions_amount_positive CHECK (amount > 0)
);

CREATE UNIQUE INDEX financial_transactions_no_unique_idx
    ON financial_transactions (transaction_no);

CREATE INDEX financial_transactions_occurred_at_idx
    ON financial_transactions (occurred_at);

CREATE INDEX financial_transactions_type_idx
    ON financial_transactions (type);

CREATE INDEX financial_transactions_category_idx
    ON financial_transactions (financial_category_id);

CREATE INDEX financial_transactions_status_idx
    ON financial_transactions (status);

CREATE INDEX financial_categories_type_idx
    ON financial_categories (type);

CREATE TRIGGER financial_categories_set_updated_at
    BEFORE UPDATE ON financial_categories
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER financial_transactions_set_updated_at
    BEFORE UPDATE ON financial_transactions
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- COGS snapshot foundation (design Bagian 2.4): unit cost frozen at sale time.
ALTER TABLE sale_items ADD COLUMN unit_cost NUMERIC(14, 2) NOT NULL DEFAULT 0;

ALTER TABLE sale_items ADD CONSTRAINT sale_items_unit_cost_non_negative CHECK (unit_cost >= 0);

INSERT INTO permissions (code, name, description)
VALUES (
    'finances',
    'Finances',
    'Access financial categories, manual transactions, and finance reports.'
);

INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id
FROM roles r
CROSS JOIN permissions p
WHERE p.code = 'finances'
AND r.code = 'admin';

COMMIT;
