-- PostgreSQL migration: append-only audit log support.

BEGIN;

CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id UUID,
    actor_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    actor_name VARCHAR(120),
    actor_email VARCHAR(160),
    actor_role VARCHAR(80),
    action VARCHAR(80) NOT NULL,
    resource_type VARCHAR(80) NOT NULL,
    resource_id BIGINT,
    resource_label VARCHAR(160),
    outcome VARCHAR(20) NOT NULL DEFAULT 'success',
    before_data JSONB,
    after_data JSONB,
    metadata JSONB,
    ip_address INET,
    user_agent TEXT,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT audit_logs_action_required CHECK (length(trim(action)) > 0),
    CONSTRAINT audit_logs_resource_type_required CHECK (length(trim(resource_type)) > 0),
    CONSTRAINT audit_logs_outcome_valid CHECK (outcome IN ('success', 'failure')),
    CONSTRAINT audit_logs_before_data_object CHECK (
        before_data IS NULL OR jsonb_typeof(before_data) = 'object'
    ),
    CONSTRAINT audit_logs_after_data_object CHECK (
        after_data IS NULL OR jsonb_typeof(after_data) = 'object'
    ),
    CONSTRAINT audit_logs_metadata_object CHECK (
        metadata IS NULL OR jsonb_typeof(metadata) = 'object'
    )
);

CREATE INDEX audit_logs_occurred_at_idx
    ON audit_logs (occurred_at DESC);

CREATE INDEX audit_logs_actor_occurred_at_idx
    ON audit_logs (actor_id, occurred_at DESC);

CREATE INDEX audit_logs_resource_occurred_at_idx
    ON audit_logs (resource_type, resource_id, occurred_at DESC);

CREATE INDEX audit_logs_action_occurred_at_idx
    ON audit_logs (action, occurred_at DESC);

CREATE INDEX audit_logs_outcome_occurred_at_idx
    ON audit_logs (outcome, occurred_at DESC);

CREATE INDEX audit_logs_request_id_idx
    ON audit_logs (request_id);

CREATE INDEX audit_logs_metadata_gin_idx
    ON audit_logs USING GIN (metadata);

COMMIT;
