-- PostgreSQL migration: members (store/POS attribution for SHU) + member auth foundation.
-- Phone is the member login identity (unique); password set by admin at registration.

BEGIN;

CREATE SEQUENCE members_member_no_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_no VARCHAR(40) NOT NULL DEFAULT (
        'MBR-' || to_char(now(), 'YYYYMMDD') || '-' ||
        lpad(nextval('members_member_no_seq')::TEXT, 6, '0')
    ),
    full_name VARCHAR(160) NOT NULL,
    phone VARCHAR(30) NOT NULL,
    email VARCHAR(160),
    password_hash TEXT NOT NULL,
    address TEXT,
    joined_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT members_full_name_required CHECK (length(trim(full_name)) > 0),
    CONSTRAINT members_phone_required CHECK (length(trim(phone)) > 0)
);

CREATE UNIQUE INDEX members_phone_unique_idx ON members (phone);
CREATE UNIQUE INDEX members_member_no_unique_idx ON members (member_no);
CREATE INDEX members_name_idx ON members (full_name);

CREATE TRIGGER members_set_updated_at
    BEFORE UPDATE ON members
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE member_refresh_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL REFERENCES members(id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX member_refresh_tokens_token_hash_unique_idx ON member_refresh_tokens (token_hash);
CREATE INDEX member_refresh_tokens_member_idx ON member_refresh_tokens (member_id);
CREATE INDEX member_refresh_tokens_expires_at_idx ON member_refresh_tokens (expires_at);

ALTER TABLE sales
    ADD COLUMN member_id BIGINT REFERENCES members(id) ON DELETE SET NULL;

CREATE INDEX sales_member_idx ON sales (member_id);

ALTER TABLE online_orders
    ADD COLUMN member_id BIGINT REFERENCES members(id) ON DELETE SET NULL;

CREATE INDEX online_orders_member_idx ON online_orders (member_id);

INSERT INTO permissions (code, name, description)
VALUES (
    'members',
    'Members',
    'Manage members and member credentials for SHU attribution.'
);

INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id
FROM roles r
CROSS JOIN permissions p
WHERE p.code = 'members'
AND r.code IN ('admin', 'cashier');

COMMIT;
