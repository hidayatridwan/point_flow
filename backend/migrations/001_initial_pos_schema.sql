    created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT payroll_period_valid CHECK (period_start <= period_end),
    CONSTRAINT payroll_base_salary_non_negative CHECK (base_salary >= 0),
    CONSTRAINT payroll_bonus_non_negative CHECK (bonus >= 0),
    CONSTRAINT payroll_deduction_non_negative CHECK (deduction >= 0),
    CONSTRAINT payroll_net_salary_non_negative CHECK ((base_salary + bonus - deduction) >= 0)
);

