CREATE VIEW v_daily_sales_report AS
SELECT
    sold_at::DATE AS sales_date,
    COUNT(*) AS transaction_count,
    COALESCE(SUM(subtotal_amount), 0) AS subtotal_amount,
    COALESCE(SUM(total_amount), 0) AS total_amount
FROM sales
WHERE status = 'completed'
GROUP BY sold_at::DATE;

CREATE VIEW v_monthly_sales_report AS
SELECT
    date_trunc('month', sold_at)::DATE AS sales_month,
    COUNT(*) AS transaction_count,
    COALESCE(SUM(subtotal_amount), 0) AS subtotal_amount,
    COALESCE(SUM(total_amount), 0) AS total_amount
FROM sales
WHERE status = 'completed'
GROUP BY date_trunc('month', sold_at)::DATE;

CREATE VIEW v_stock_report AS
SELECT
    ps.id AS product_sku_id,
    p.id AS product_id,
    p.name AS product_name,
    ps.sku,
    ps.barcode,
    c.name AS category_name,
    ps.purchase_price,
    ps.selling_price,
    ps.stock,
    ps.minimum_stock,
    u.code AS unit,
    COALESCE((
        SELECT SUM(poi.quantity_ordered - poi.quantity_received)
        FROM purchase_order_items poi
        JOIN purchase_orders po ON po.id = poi.purchase_order_id
        WHERE poi.product_sku_id = ps.id
            AND po.status IN ('ordered', 'partially_received')
    ), 0) AS quantity_on_order,
    (ps.stock <= ps.minimum_stock) AS is_low_stock,
    (p.is_active AND ps.is_active) AS is_active
FROM products p
JOIN product_skus ps ON ps.product_id = p.id
LEFT JOIN product_categories c ON c.id = p.category_id
JOIN units u ON u.id = ps.unit_id
WHERE p.deleted_at IS NULL AND ps.deleted_at IS NULL;

CREATE VIEW v_purchase_order_report AS
SELECT
    po.id,
    po.po_no,
    po.order_date,
    po.expected_date,
    s.name AS supplier_name,
    po.status,
    COUNT(poi.id) AS item_count,
    COALESCE(SUM(poi.quantity_ordered), 0) AS total_quantity_ordered,
    COALESCE(SUM(poi.quantity_received), 0) AS total_quantity_received,
    COALESCE(SUM(poi.quantity_ordered - poi.quantity_received), 0) AS total_quantity_remaining,
    po.subtotal_amount,
    po.created_at,
    po.updated_at
FROM purchase_orders po
JOIN suppliers s ON s.id = po.supplier_id
LEFT JOIN purchase_order_items poi ON poi.purchase_order_id = po.id
GROUP BY po.id, s.id;

CREATE VIEW v_goods_receipt_report AS
SELECT
    gr.id,
    gr.gr_no,
    gr.received_at,
    gr.status,
    po.po_no,
    s.name AS supplier_name,
    COUNT(gri.id) AS item_count,
    COALESCE(SUM(gri.quantity_received), 0) AS total_quantity_received,
    COALESCE(SUM(gri.line_total), 0) AS total_amount,
    gr.created_at,
    gr.updated_at
FROM goods_receipts gr
JOIN purchase_orders po ON po.id = gr.purchase_order_id
JOIN suppliers s ON s.id = po.supplier_id
LEFT JOIN goods_receipt_items gri ON gri.goods_receipt_id = gr.id
GROUP BY gr.id, po.id, s.id;

CREATE VIEW v_stock_adjustment_report AS
SELECT
    sa.id,
    sa.adjustment_no,
    sa.adjusted_at,
    sa.status,
    sa.reason,
    COUNT(sai.id) AS item_count,
    COALESCE(SUM(CASE WHEN sai.quantity_delta > 0 THEN sai.quantity_delta ELSE 0 END), 0) AS total_quantity_increased,
    COALESCE(SUM(CASE WHEN sai.quantity_delta < 0 THEN abs(sai.quantity_delta) ELSE 0 END), 0) AS total_quantity_decreased,
    sa.created_by,
    sa.posted_at,
    sa.posted_by,
    sa.created_at,
    sa.updated_at
FROM stock_adjustments sa
LEFT JOIN stock_adjustment_items sai ON sai.stock_adjustment_id = sa.id
GROUP BY sa.id;

CREATE VIEW v_payroll_report AS
SELECT
    period_start,
    period_end,
    COUNT(*) AS slip_count,
    COALESCE(SUM(base_salary), 0) AS total_base_salary,
    COALESCE(SUM(bonus), 0) AS total_bonus,
    COALESCE(SUM(deduction), 0) AS total_deduction,
    COALESCE(SUM(net_salary), 0) AS total_net_salary
FROM payroll_slips
GROUP BY period_start, period_end;

