-- PostgreSQL migration: sales return and cash refund support.

BEGIN;

CREATE TYPE sale_return_status AS ENUM ('completed', 'cancelled');

ALTER TYPE stock_movement_type ADD VALUE 'sale_return';

CREATE SEQUENCE sale_return_no_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE sale_returns (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    return_no VARCHAR(40) NOT NULL DEFAULT (
        'RET-' || to_char(now(), 'YYYYMMDD') || '-' ||
        lpad(nextval('sale_return_no_seq')::TEXT, 6, '0')
    ),
    sale_id BIGINT NOT NULL REFERENCES sales(id) ON DELETE RESTRICT,
    returned_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    cashier_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    cash_register_session_id BIGINT NOT NULL REFERENCES cash_register_sessions(id) ON DELETE RESTRICT,
    subtotal_amount NUMERIC(14, 2) NOT NULL DEFAULT 0,
    refund_amount NUMERIC(14, 2) NOT NULL DEFAULT 0,
    status sale_return_status NOT NULL DEFAULT 'completed',
    reason TEXT,
    notes TEXT,
    cancelled_at TIMESTAMPTZ,
    cancelled_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    cancel_reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT sale_returns_subtotal_non_negative CHECK (subtotal_amount >= 0),
    CONSTRAINT sale_returns_refund_non_negative CHECK (refund_amount >= 0),
    CONSTRAINT sale_returns_refund_matches_subtotal CHECK (refund_amount = subtotal_amount)
);

CREATE UNIQUE INDEX sale_returns_return_no_unique_idx ON sale_returns (return_no);
CREATE INDEX sale_returns_sale_idx ON sale_returns (sale_id);
CREATE INDEX sale_returns_returned_at_idx ON sale_returns (returned_at);
CREATE INDEX sale_returns_cashier_idx ON sale_returns (cashier_id);
CREATE INDEX sale_returns_cash_register_session_idx ON sale_returns (cash_register_session_id);
CREATE INDEX sale_returns_status_idx ON sale_returns (status);

CREATE TABLE sale_return_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_return_id BIGINT NOT NULL REFERENCES sale_returns(id) ON DELETE CASCADE,
    sale_item_id BIGINT NOT NULL REFERENCES sale_items(id) ON DELETE RESTRICT,
    product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
    product_sku_id BIGINT NOT NULL REFERENCES product_skus(id) ON DELETE RESTRICT,
    product_name VARCHAR(160) NOT NULL,
    product_sku VARCHAR(64) NOT NULL,
    unit VARCHAR(30) NOT NULL,
    quantity NUMERIC(14, 3) NOT NULL,
    unit_price NUMERIC(14, 2) NOT NULL,
    line_total NUMERIC(14, 2) GENERATED ALWAYS AS (quantity * unit_price) STORED,
    restock BOOLEAN NOT NULL DEFAULT TRUE,
    reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT sale_return_items_quantity_positive CHECK (quantity > 0),
    CONSTRAINT sale_return_items_unit_price_non_negative CHECK (unit_price >= 0)
);

CREATE INDEX sale_return_items_sale_return_idx ON sale_return_items (sale_return_id);
CREATE INDEX sale_return_items_sale_item_idx ON sale_return_items (sale_item_id);
CREATE INDEX sale_return_items_product_idx ON sale_return_items (product_id);
CREATE INDEX sale_return_items_product_sku_idx ON sale_return_items (product_sku_id);

ALTER TABLE stock_movements
    ADD COLUMN sale_return_id BIGINT REFERENCES sale_returns(id) ON DELETE SET NULL,
    ADD COLUMN sale_return_item_id BIGINT REFERENCES sale_return_items(id) ON DELETE SET NULL;

CREATE INDEX stock_movements_sale_return_idx ON stock_movements (sale_return_id);

