-- PostgreSQL migration: cash drawer manual movement support.

BEGIN;

CREATE TYPE cash_drawer_movement_type AS ENUM (
    'cash_in',
    'cash_out',
    'cash_drop',
    'petty_cash'
);

CREATE TYPE cash_drawer_movement_direction AS ENUM (
    'in',
    'out'
);

CREATE TYPE cash_drawer_movement_status AS ENUM (
    'completed',
    'cancelled'
);

CREATE SEQUENCE cash_drawer_movement_no_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE cash_drawer_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movement_no VARCHAR(40) NOT NULL DEFAULT (
        'CDM-' || to_char(now(), 'YYYYMMDD') || '-' ||
        lpad(nextval('cash_drawer_movement_no_seq')::TEXT, 6, '0')
    ),
    cash_register_session_id BIGINT NOT NULL REFERENCES cash_register_sessions(id) ON DELETE RESTRICT,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    movement_type cash_drawer_movement_type NOT NULL,
    direction cash_drawer_movement_direction NOT NULL,
    amount NUMERIC(14, 2) NOT NULL,
    reason TEXT,
    notes TEXT,
    status cash_drawer_movement_status NOT NULL DEFAULT 'completed',
    cancelled_at TIMESTAMPTZ,
    cancelled_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    cancel_reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT cash_drawer_movements_amount_positive CHECK (amount > 0),
    CONSTRAINT cash_drawer_movements_type_direction_valid CHECK (
        (movement_type = 'cash_in' AND direction = 'in')
        OR (movement_type IN ('cash_out', 'cash_drop', 'petty_cash') AND direction = 'out')
    )
);

CREATE UNIQUE INDEX cash_drawer_movements_no_unique_idx
    ON cash_drawer_movements (movement_no);

CREATE INDEX cash_drawer_movements_session_status_idx
    ON cash_drawer_movements (cash_register_session_id, status);

CREATE INDEX cash_drawer_movements_occurred_at_idx
    ON cash_drawer_movements (occurred_at);

CREATE INDEX cash_drawer_movements_created_by_idx
    ON cash_drawer_movements (created_by);

CREATE INDEX cash_drawer_movements_type_idx
    ON cash_drawer_movements (movement_type);

CREATE INDEX cash_drawer_movements_status_idx
    ON cash_drawer_movements (status);

CREATE TRIGGER cash_drawer_movements_set_updated_at
    BEFORE UPDATE ON cash_drawer_movements
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();

COMMIT;
