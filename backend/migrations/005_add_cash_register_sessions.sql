-- PostgreSQL migration: cash register and drawer session support.

BEGIN;

CREATE TYPE cash_register_status AS ENUM ('active', 'inactive');
CREATE TYPE cash_register_session_status AS ENUM ('open', 'closed');

CREATE SEQUENCE cash_register_session_no_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE cash_registers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(40) NOT NULL,
    name VARCHAR(120) NOT NULL,
    description TEXT,
    status cash_register_status NOT NULL DEFAULT 'active',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at TIMESTAMPTZ
);

CREATE UNIQUE INDEX cash_registers_code_unique_idx
    ON cash_registers (lower(code))
    WHERE deleted_at IS NULL;

CREATE INDEX cash_registers_status_idx ON cash_registers (status);

CREATE TABLE cash_register_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_no VARCHAR(40) NOT NULL DEFAULT (
        'CRS-' || to_char(now(), 'YYYYMMDD') || '-' ||
        lpad(nextval('cash_register_session_no_seq')::TEXT, 6, '0')
    ),
    cash_register_id BIGINT NOT NULL REFERENCES cash_registers(id) ON DELETE RESTRICT,
    opened_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    opened_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    opening_cash NUMERIC(14, 2) NOT NULL DEFAULT 0,
    opening_notes TEXT,
    closed_at TIMESTAMPTZ,
    closed_by BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    closing_cash_counted NUMERIC(14, 2),
    expected_cash NUMERIC(14, 2),
    cash_difference NUMERIC(14, 2),
    closing_notes TEXT,
    status cash_register_session_status NOT NULL DEFAULT 'open',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT cash_register_sessions_opening_cash_non_negative CHECK (opening_cash >= 0),
    CONSTRAINT cash_register_sessions_closing_cash_counted_non_negative CHECK (
        closing_cash_counted IS NULL OR closing_cash_counted >= 0
    ),
    CONSTRAINT cash_register_sessions_expected_cash_non_negative CHECK (
        expected_cash IS NULL OR expected_cash >= 0
    )
);

CREATE UNIQUE INDEX cash_register_sessions_session_no_unique_idx
    ON cash_register_sessions (session_no);

CREATE INDEX cash_register_sessions_register_status_idx
    ON cash_register_sessions (cash_register_id, status);

CREATE INDEX cash_register_sessions_opened_at_idx
    ON cash_register_sessions (opened_at);

CREATE UNIQUE INDEX cash_register_sessions_one_open_per_register_idx
    ON cash_register_sessions (cash_register_id)
    WHERE status = 'open';

ALTER TABLE sales
    ADD COLUMN cash_register_session_id BIGINT REFERENCES cash_register_sessions(id) ON DELETE RESTRICT;

CREATE INDEX sales_cash_register_session_idx ON sales (cash_register_session_id);

CREATE TRIGGER cash_registers_set_updated_at
    BEFORE UPDATE ON cash_registers
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER cash_register_sessions_set_updated_at
    BEFORE UPDATE ON cash_register_sessions
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();

COMMIT;
