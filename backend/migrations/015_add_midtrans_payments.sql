-- PostgreSQL migration: fondasi pembayaran non-tunai Midtrans Snap.
-- Mode pembayaran toko (`payment_mode` = manual | midtrans, default manual)
-- bersifat eksklusif; pembayaran pending tidak menyentuh stok/saldo.
-- Stok/sale baru dibuat saat webhook settlement terverifikasi (fase 2+).

-- Nilai enum untuk checkout online via Midtrans. WAJIB di luar blok
-- transaksi: PostgreSQL menolak ALTER TYPE ... ADD VALUE di dalam
-- transaction block. Idempoten bila file dijalankan ulang.
ALTER TYPE online_order_payment_method ADD VALUE IF NOT EXISTS 'midtrans';

BEGIN;

INSERT INTO store_settings (key, value)
VALUES ('payment_mode', 'manual')
ON CONFLICT DO NOTHING;

CREATE TABLE midtrans_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id VARCHAR(50) NOT NULL UNIQUE,
    source_type VARCHAR(10) NOT NULL,
    gross_amount INTEGER NOT NULL,
    snap_token TEXT,
    redirect_url TEXT,
    transaction_status VARCHAR(30) NOT NULL DEFAULT 'pending',
    fraud_status VARCHAR(30),
    payment_type VARCHAR(40),
    va_info JSONB,
    raw_notification JSONB,
    sale_id BIGINT REFERENCES sales(id),
    online_order_id BIGINT REFERENCES online_orders(id),
    -- Konteks charge untuk settlement: item yang dibeli (JSON array
    -- {product_sku_id, quantity}), member, dan catatan kasir. Dibaca webhook
    -- saat transisi pertama ke settlement untuk membuat sale + kurangi stok.
    items JSONB,
    member_id BIGINT REFERENCES members(id) ON DELETE SET NULL,
    notes TEXT,
    expires_at TIMESTAMPTZ,
    settled_at TIMESTAMPTZ,
    created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT midtrans_payments_order_id_format CHECK (
        length(trim(order_id)) > 0 AND order_id ~ '^[A-Za-z0-9\-_.~]+$'
    ),
    CONSTRAINT midtrans_payments_source_type_valid CHECK (
        source_type IN ('pos', 'online')
    ),
    CONSTRAINT midtrans_payments_gross_amount_non_negative CHECK (gross_amount >= 0)
);

CREATE INDEX midtrans_payments_order_id_idx ON midtrans_payments (order_id);
CREATE INDEX midtrans_payments_transaction_status_idx
    ON midtrans_payments (transaction_status);

CREATE TRIGGER midtrans_payments_set_updated_at
    BEFORE UPDATE ON midtrans_payments
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

COMMIT;
